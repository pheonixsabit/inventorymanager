CREATE TABLE IF NOT EXISTS products (
	sku TEXT PRIMARY KEY,
	name TEXT NOT NULL,
	category TEXT,
	cost_cents INTEGER NOT NULL DEFAULT 0,
	price_cents INTEGER NOT NULL DEFAULT 0,
	competitor_price_cents INTEGER,
	stock_quantity INTEGER NOT NULL DEFAULT 0,
	reorder_point INTEGER NOT NULL DEFAULT 0,
	target_margin_percent REAL,
	created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
	updated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS pricing_rules (
	id INTEGER PRIMARY KEY CHECK (id = 1),
	default_margin_percent REAL NOT NULL DEFAULT 35,
	marketplace_fee_percent REAL NOT NULL DEFAULT 8,
	shipping_cents INTEGER NOT NULL DEFAULT 250,
	minimum_profit_cents INTEGER NOT NULL DEFAULT 400,
	undercut_percent REAL NOT NULL DEFAULT 2,
	price_ending TEXT NOT NULL DEFAULT '.99',
	updated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS stock_movements (
	id INTEGER PRIMARY KEY AUTOINCREMENT,
	sku TEXT NOT NULL REFERENCES products(sku),
	quantity_delta INTEGER NOT NULL,
	reason TEXT,
	created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS import_jobs (
	id INTEGER PRIMARY KEY AUTOINCREMENT,
	filename TEXT NOT NULL,
	status TEXT NOT NULL DEFAULT 'pending',
	created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS export_jobs (
	id INTEGER PRIMARY KEY AUTOINCREMENT,
	format TEXT NOT NULL DEFAULT 'csv',
	status TEXT NOT NULL DEFAULT 'pending',
	created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);

